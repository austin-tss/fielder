import puppeteer from 'puppeteer-core';
import { start } from './mock-server.mjs';
const SHOTS = process.env.SHOTS || '';
function fail(m) { throw new Error(m); }
const server = await start(0);
const base = 'http://127.0.0.1:' + server.address().port;
const browser = await puppeteer.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const page = await browser.newPage();
await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 2 });
const waitText = (t) => page.waitForFunction((t) => document.body.innerText.includes(t), { timeout: 15000 }, t);
const cards = () => page.$$eval('#jl .job', (e) => e.map((x) => x.querySelector('b').textContent));
try {
  await page.goto(base + '/?api=' + encodeURIComponent(base + '/exec'), { waitUntil: 'networkidle0' });
  await page.evaluate(() => localStorage.removeItem('fdPer'));
  await page.click('#brand');
  await waitText('Enter your PIN');
  let answer = false; const asked = [];
  page.on('dialog', (d) => { asked.push(d.message()); answer ? d.accept() : d.dismiss(); });
  for (const d of '1234') await page.evaluate((d) => [...document.querySelectorAll('.pin button')].find((b) => b.textContent === d).click(), d);
  await waitText('New customer quote');
  await page.waitForFunction(() => document.getElementById('qncount').textContent === '2 waiting to be quoted');
  if (SHOTS) await page.screenshot({ path: SHOTS + '/qn_row_home.png' });
  // Local-only fake jobs (never sent to the server).
  await page.evaluate(() => { for (let i = 1; i <= 30; i++) jobs.push({ id: 'T' + i, name: 'Test Job ' + String(i).padStart(2, '0'), address: '', status: i % 2 ? 'complete' : 'sent', created: '2026-09-' + String(i).padStart(2, '0') + 'T12:00:00Z', items: [], crew: [], photos: [] }); render(); });
  let c = await cards();
  if (c.length !== 10) fail('default should show 10, got ' + c.length);
  if ((await page.$eval('#pginfo', (e) => e.textContent)) !== 'Page 1 of 2') fail('page info wrong');
  if (SHOTS) await page.screenshot({ path: SHOTS + '/show_picker_home.png' });
  await page.select('#persel', '5');
  c = await cards();
  if (c.length !== 5) fail('5 not applied');
  if (c[0] !== 'Finished Pine' && c[0] !== 'Test Job 29') fail('not newest first: ' + c[0]);
  if ((await page.$eval('#pginfo', (e) => e.textContent)) !== 'Page 1 of 4') fail('5 per page info wrong');
  await page.click('#pgnext');
  const p2 = await cards();
  if (p2.length !== 5 || p2[0] === c[0]) fail('next page failed');
  if ((await page.$eval('#pginfo', (e) => e.textContent)) !== 'Page 2 of 4') fail('page 2 info wrong');
  if (SHOTS) await page.screenshot({ path: SHOTS + '/pager_page2.png' });
  await page.click('#pgprev');
  if ((await cards())[0] !== c[0]) fail('prev failed');
  await page.click('#pgnext');
  await page.type('#find', 'Test Job 1');
  c = await cards();
  if (!c.every((n) => n.startsWith('Test Job 1'))) fail('search + paging broken');
  if (await page.$('#pginfo') && (await page.$eval('#pginfo', (e) => e.textContent)) !== 'Page 1 of 1') fail('search should reset to page 1');
  await page.evaluate(() => { LQ = ''; navHome(); });
  await page.reload({ waitUntil: 'networkidle0' });
  if ((await page.evaluate(() => localStorage.fdPer)) !== '5') fail('choice not remembered');
  await page.evaluate(() => { for (let i = 1; i <= 30; i++) jobs.push({ id: 'T' + i, name: 'Test Job ' + String(i).padStart(2, '0'), address: '', status: i % 2 ? 'complete' : 'sent', created: '2026-09-' + String(i).padStart(2, '0') + 'T12:00:00Z', items: [], crew: [], photos: [] }); render(); });
  if ((await page.$eval('#persel', (e) => e.value)) !== '5') fail('select not remembered');
  await page.click('#row-fq');
  await page.waitForSelector('#persel');
  if ((await cards()).length !== 5) fail('finished quotes not paged');
  if (SHOTS) await page.screenshot({ path: SHOTS + '/show_picker_finished.png' });
  await page.click('#brand');
  await waitText('New customer quote');
  await page.evaluate(() => newq());
  await page.waitForSelector('#nm');
  await page.click('#brand');
  if (asked.length) fail('untouched form should not ask: ' + asked.join('|'));
  await waitText('New customer quote');
  await page.evaluate(() => newq());
  await page.type('#nm', 'Unsaved Person');
  await page.click('#brand');
  if (asked[0] !== 'Leave without saving?') fail('no unsaved prompt');
  if (!(await page.$('#nm'))) fail('should stay on the form after Cancel');
  answer = true;
  await page.click('#brand');
  await waitText('Finished quotes');
  await page.evaluate(() => { jobs.push({ id: 'LONG', est: 'FT-EST-2026-0005', name: 'Jesse', address: '3660 Old Bainbridge Road Northwest Apartment 12B, Tallahassee, FL 32303', email: 'jesse@example.com', status: 'approved', created: '2026-10-28T12:00:00Z', items: [], total: 900, crew: [], photos: [] }); LQ = 'Jesse'; render(); });
  await page.waitForSelector('#jl .job');
  const cardText = await page.$eval('#jl .job', (e) => e.innerText);
  if (!cardText.includes('Tallahassee, FL 32303')) fail('card cut the address');
  if (SHOTS) await page.screenshot({ path: SHOTS + '/long_address_card.png' });
  await page.evaluate(() => mview('LONG'));
  await waitText('Old Bainbridge Road Northwest Apartment 12B, Tallahassee, FL 32303');
  if (SHOTS) await page.screenshot({ path: SHOTS + '/long_address_detail.png' });
  if (!(await page.evaluate(() => addrBad('3660') && !addrBad('3660 Main St, Tallahassee, FL') && !addrBad('')))) fail('addrBad wrong');
  await page.evaluate(() => { LQ = ''; });
  console.log('fielder paging e2e ok');
} finally { await browser.close(); server.close(); }
